"""Rename the custom models x_* to jin_* in the database (their tables follow).

Generated by _tools/rename/gen_migrations.py. The same script ships in every module of
the rename set; whichever module upgrades first does the work, the others find the
marker and return. Map: MAP_FILE next to this file (old_model, new_model, old_table,
new_table, modules of the rename set).

Runs before the modules load, so the ORM finds every model under its new name. Records
keep their ids; nothing is dropped and recreated:
- ir_model.model (and state 'base': Odoo only allows x_ names for Studio-made 'manual'
  models)
- the table, its id sequence, its index / constraint names (ir_model_constraint follows)
- every column holding a model name (model, res_model, model_name, ...;
  ir_model_fields.relation, ir_filters.model_id, ir_exports.resource, ir_sequence.code),
  and 'model,id' reference values
- Odoo's own xmlids built from model names (model_*, field_*, selection__*,
  constraint_*) and the xmlids of modules outside the rename set; the set's own xmlids
  are renamed by the pre-30 script
- model and table names inside stored text: views, server actions, domains, contexts,
  filters, rules, automations, templates, export lists, report names
Many2many tables keep their names (the code names them explicitly).
"""

import csv
import hashlib
import logging
import os
import re

from odoo.tools import SQL

_logger = logging.getLogger(__name__)

MAP_FILE = "rename_models_trial.csv"
MARKER = "studio_rename.helpdesk_models"
X_PREFIX_RE = "(^|[^A-Za-z0-9])x_"
MODEL_COLUMNS = [
    "model",
    "res_model",
    "model_name",
    "res_model_name",
    "src_model",
    "parent_res_model",
    "document_model",
]
EXTRA_COLUMNS = [
    ("ir_model_fields", "relation"),
    ("ir_filters", "model_id"),
    ("ir_exports", "resource"),
    ("ir_sequence", "code"),
]
TEXT_COLUMNS = {
    "ir_ui_view": ["arch_db", "arch_prev"],
    "ir_ui_view_custom": ["arch"],
    "ir_act_server": ["code", "update_path", "value"],
    "ir_server_object_lines": ["value"],
    "ir_act_window": ["domain", "context"],
    "ir_act_client": ["params", "context"],
    "ir_filters": ["domain", "context", "sort"],
    "ir_rule": ["domain_force"],
    "base_automation": ["filter_domain", "filter_pre_domain"],
    "mail_template": [
        "subject",
        "body_html",
        "email_from",
        "email_to",
        "email_cc",
        "partner_to",
        "reply_to",
        "lang",
        "scheduled_date",
        "report_name",
    ],
    "sms_template": ["body"],
    "mail_alias": ["alias_defaults"],
    "ir_exports_line": ["name"],
    "ir_model_fields": ["related", "depends", "compute", "domain"],
    "ir_model": ["order"],
    "ir_act_report_xml": ["print_report_name", "attachment"],
    "studio_approval_rule": ["domain"],
    "account_report_expression": ["formula"],
}
META_XMLID_MODELS = (
    "ir.model",
    "ir.model.fields",
    "ir.model.fields.selection",
    "ir.model.constraint",
    "ir.model.relation",
)


class RenameConflictError(Exception):
    """A new name already exists in the database: resolve it before upgrading."""


def _load_map():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), MAP_FILE)
    with open(path, encoding="utf-8", newline="") as fh:
        rows = [
            (
                r["old_model"],
                r["new_model"],
                r["old_table"],
                r["new_table"],
                r["modules"].split(";"),
            )
            for r in csv.DictReader(fh)
        ]
    key = repr(sorted(r[:4] for r in rows)).encode()
    return rows, hashlib.sha1(key, usedforsecurity=False).hexdigest()


def _rule(mapping):
    # same token rule as the code: not inside a longer word, a following "__" is allowed
    names = "|".join(map(re.escape, sorted(mapping, key=len, reverse=True)))
    return re.compile(r"(?<![A-Za-z0-9])(" + names + r")(?![A-Za-z0-9]|_(?!_))")


def _like_prefix(name):
    return name.replace("_", r"\_") + r"\_%"


def _column_type(cr, table, column):
    cr.execute(
        "SELECT data_type FROM information_schema.columns "
        "WHERE table_name = %s AND column_name = %s",
        (table, column),
    )
    row = cr.fetchone()
    return row and row[0]


def _exists(cr, relname):
    cr.execute("SELECT 1 FROM pg_class WHERE relname = %s", (relname,))
    return bool(cr.fetchone())


def _rename_table(cr, old_t, new_t):
    if not _exists(cr, old_t):
        return
    if _exists(cr, new_t):
        raise RenameConflictError(f"Table {new_t} already exists ({old_t}).")
    cr.execute(
        SQL(
            "ALTER TABLE %s RENAME TO %s",
            SQL.identifier(old_t),
            SQL.identifier(new_t),
        )
    )
    old_seq, new_seq = f"{old_t}_id_seq", f"{new_t}_id_seq"
    if _exists(cr, old_seq) and not _exists(cr, new_seq):
        cr.execute(
            SQL(
                "ALTER SEQUENCE %s RENAME TO %s",
                SQL.identifier(old_seq),
                SQL.identifier(new_seq),
            )
        )
    # Odoo finds indexes and constraints by name:
    # <table>__<column>_index, <table>_<key>, <table>_pkey
    cr.execute(
        "SELECT c.relname FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid "
        "JOIN pg_class t ON t.oid = i.indrelid WHERE t.relname = %s "
        "AND c.relname LIKE %s",
        (new_t, _like_prefix(old_t)),
    )
    for (idx,) in cr.fetchall():
        new_idx = new_t + idx[len(old_t) :]
        if len(new_idx) <= 63 and not _exists(cr, new_idx):
            cr.execute(
                SQL(
                    "ALTER INDEX %s RENAME TO %s",
                    SQL.identifier(idx),
                    SQL.identifier(new_idx),
                )
            )
    cr.execute(
        "SELECT con.conname FROM pg_constraint con "
        "JOIN pg_class t ON t.oid = con.conrelid WHERE t.relname = %s "
        "AND con.contype IN ('c', 'u', 'x', 'f') AND con.conname LIKE %s",
        (new_t, _like_prefix(old_t)),
    )
    for (con,) in cr.fetchall():
        new_con = new_t + con[len(old_t) :]
        if len(new_con) <= 63:
            cr.execute(
                SQL(
                    "ALTER TABLE %s RENAME CONSTRAINT %s TO %s",
                    SQL.identifier(new_t),
                    SQL.identifier(con),
                    SQL.identifier(new_con),
                )
            )


def _rename_constraint_records(cr, model_id, old_t, new_t):
    cr.execute(
        "UPDATE ir_model_data d SET name = 'constraint_' || %s || substr(d.name, %s) "
        "FROM ir_model_constraint c WHERE d.model = 'ir.model.constraint' "
        "AND d.res_id = c.id AND c.model = %s AND d.name LIKE %s",
        (
            new_t,
            len("constraint_" + old_t) + 1,
            model_id,
            "constraint" + r"\_" + _like_prefix(old_t),
        ),
    )
    cr.execute(
        "UPDATE ir_model_constraint SET name = %s || substr(name, %s) "
        "WHERE model = %s AND name LIKE %s",
        (new_t, len(old_t) + 1, model_id, _like_prefix(old_t)),
    )


def _rename_models(cr, rows):
    done = 0
    for old, new, old_t, new_t, _modules in rows:
        cr.execute("SELECT id FROM ir_model WHERE model = %s", (old,))
        row = cr.fetchone()
        if not row:
            continue
        cr.execute("SELECT 1 FROM ir_model WHERE model = %s", (new,))
        if cr.fetchone():
            raise RenameConflictError(f"Model {new} already exists ({old}).")
        # Studio models are 'manual', and Odoo only allows x_ names for those;
        # the model is declared in code now
        cr.execute(
            "UPDATE ir_model SET model = %s, state = 'base' WHERE id = %s",
            (new, row[0]),
        )
        _rename_table(cr, old_t, new_t)
        _rename_constraint_records(cr, row[0], old_t, new_t)
        done += 1
    _logger.info("Studio model rename: %s models renamed", done)


def _model_columns(cr):
    cr.execute(
        "SELECT table_name, column_name FROM information_schema.columns "
        "WHERE table_schema = 'public' AND column_name = ANY(%s) "
        "AND data_type IN ('character varying', 'text')",
        (MODEL_COLUMNS,),
    )
    targets = cr.fetchall()
    return targets + [(t, c) for t, c in EXTRA_COLUMNS if _column_type(cr, t, c)]


def _rename_model_columns(cr, models):
    for table, column in _model_columns(cr):
        tbl, col = SQL.identifier(table), SQL.identifier(column)
        cr.execute(
            SQL(
                "SELECT DISTINCT %s FROM %s WHERE %s = ANY(%s)",
                col,
                tbl,
                col,
                list(models),
            )
        )
        for (old,) in cr.fetchall():
            cr.execute(
                SQL(
                    "UPDATE %s SET %s = %s WHERE %s = %s",
                    tbl,
                    col,
                    models[old],
                    col,
                    old,
                )
            )
            _logger.info(
                "Studio model rename: %s.%s %s -> %s, %s rows",
                table,
                column,
                old,
                models[old],
                cr.rowcount,
            )
    # 'model,id' references: stored reference fields and properties
    cr.execute(
        "SELECT model, name FROM ir_model_fields WHERE ttype = 'reference' AND store"
    )
    refs = [(m.replace(".", "_"), f) for m, f in cr.fetchall()]
    refs += [("ir_property", "res_id"), ("ir_property", "value_reference")]
    for table, column in refs:
        if not _column_type(cr, table, column):
            continue
        tbl, col = SQL.identifier(table), SQL.identifier(column)
        for old, new in models.items():
            prefix = old.replace("_", r"\_") + ",%"
            cr.execute(
                SQL(
                    "UPDATE %s SET %s = %s || substr(%s, %s) WHERE %s LIKE %s",
                    tbl,
                    col,
                    new + ",",
                    col,
                    len(old) + 2,
                    col,
                    prefix,
                )
            )


def _rename_xmlids(cr, rule, mapping, own_modules):
    cr.execute(
        "SELECT id, module, name, model FROM ir_model_data WHERE name ~ %s",
        (X_PREFIX_RE,),
    )
    done = 0
    for xid, module, name, model in cr.fetchall():
        if module in own_modules and model not in META_XMLID_MODELS:
            continue
        new = rule.sub(lambda m: mapping[m.group(1)], name)
        if new == name:
            continue
        cr.execute(
            "SELECT 1 FROM ir_model_data WHERE module = %s AND name = %s", (module, new)
        )
        if cr.fetchone():
            _logger.warning(
                "Studio model rename: xmlid %s.%s -> %s exists already, kept",
                module,
                name,
                new,
            )
            continue
        cr.execute("UPDATE ir_model_data SET name = %s WHERE id = %s", (new, xid))
        done += 1
    _logger.info("Studio model rename: %s xmlids renamed", done)


def _rename_column_text(cr, rule, mapping, table, column):
    ctype = _column_type(cr, table, column)
    if not ctype:
        return
    tbl, col = SQL.identifier(table), SQL.identifier(column)
    cr.execute(
        SQL(
            "SELECT id, %s::text FROM %s WHERE %s::text ~ %s",
            col,
            tbl,
            col,
            X_PREFIX_RE,
        )
    )
    count = 0
    for rid, text in cr.fetchall():
        new = rule.sub(lambda m: mapping[m.group(1)], text)
        if new != text:
            value = SQL("%s::jsonb", new) if ctype == "jsonb" else SQL("%s", new)
            cr.execute(SQL("UPDATE %s SET %s = %s WHERE id = %s", tbl, col, value, rid))
            count += 1
    if count:
        _logger.info("Studio model rename: %s.%s %s rows updated", table, column, count)


def migrate(cr, version):
    if not version:
        return
    rows, digest = _load_map()
    cr.execute("SELECT value FROM ir_config_parameter WHERE key = %s", (MARKER,))
    row = cr.fetchone()
    if row and row[0] == digest:
        return
    models = {r[0]: r[1] for r in rows}
    mapping = {**models, **{r[2]: r[3] for r in rows}}
    own_modules = {m for r in rows for m in r[4]}
    _rename_models(cr, rows)
    _rename_model_columns(cr, models)
    rule = _rule(mapping)
    _rename_xmlids(cr, rule, mapping, own_modules)
    for table, columns in TEXT_COLUMNS.items():
        for column in columns:
            _rename_column_text(cr, rule, mapping, table, column)
    cr.execute("DELETE FROM ir_config_parameter WHERE key = %s", (MARKER,))
    cr.execute(
        "INSERT INTO ir_config_parameter (key, value, create_date, write_date) "
        "VALUES (%s, %s, now() at time zone 'UTC', now() at time zone 'UTC')",
        (MARKER, digest),
    )
