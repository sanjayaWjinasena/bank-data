"""Rename the Studio-numbered XML ids to their clean names in the database.

Generated by _tools/rename/gen_migrations.py. The same script ships in every module of
the rename set; whichever module upgrades first does the work, the others find the
marker and return. Map: MAP_FILE next to this file (module, old_xmlid, new_xmlid).

Runs before the modules load their data, so each record keeps its database id (no record
is deleted and recreated):
- ir_model_data.name, per module
- qualified references (module.old_id) stored as text: view keys, view arches, report
  names, server action code, window action contexts and domains, mail template bodies
"""

import csv
import hashlib
import logging
import os
import re

from odoo.tools import SQL

_logger = logging.getLogger(__name__)

MAP_FILE = "rename_xmlids_trial.csv"
MARKER = "studio_rename.helpdesk_xmlids"
TEXT_COLUMNS = {
    "ir_ui_view": ["key", "arch_db", "arch_prev"],
    "ir_ui_view_custom": ["arch"],
    "ir_act_report_xml": ["report_name", "report_file"],
    "ir_act_server": ["code"],
    "ir_act_window": ["context", "domain"],
    "mail_template": ["body_html"],
}


def _load_map():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), MAP_FILE)
    with open(path, encoding="utf-8", newline="") as fh:
        rows = [
            (r["module"], r["old_xmlid"], r["new_xmlid"]) for r in csv.DictReader(fh)
        ]
    digest = hashlib.sha1(repr(sorted(rows)).encode(), usedforsecurity=False)
    return rows, digest.hexdigest()


def _column_type(cr, table, column):
    cr.execute(
        "SELECT data_type FROM information_schema.columns "
        "WHERE table_name = %s AND column_name = %s",
        (table, column),
    )
    row = cr.fetchone()
    return row and row[0]


def _rename_xmlids(cr, rows):
    done = kept = 0
    for module, old, new in rows:
        cr.execute(
            "SELECT 1 FROM ir_model_data WHERE module = %s AND name = %s", (module, new)
        )
        if cr.fetchone():
            kept += 1
            _logger.warning(
                "Studio xmlid rename: %s.%s exists already, %s kept", module, new, old
            )
            continue
        cr.execute(
            "UPDATE ir_model_data SET name = %s WHERE module = %s AND name = %s",
            (new, module, old),
        )
        done += cr.rowcount
    _logger.info("Studio xmlid rename: %s xmlids renamed, %s kept", done, kept)


def _rename_column_text(cr, rule, qualified, prefilter, table, column):
    ctype = _column_type(cr, table, column)
    if not ctype:
        return
    col = SQL.identifier(column)
    cr.execute(
        SQL(
            "SELECT id, %s::text FROM %s WHERE %s::text ~ %s",
            col,
            SQL.identifier(table),
            col,
            prefilter,
        )
    )
    count = 0
    for rid, text in cr.fetchall():
        new = rule.sub(lambda m: qualified[m.group(1)], text)
        if new != text:
            value = SQL("%s::jsonb", new) if ctype == "jsonb" else SQL("%s", new)
            cr.execute(
                SQL(
                    "UPDATE %s SET %s = %s WHERE id = %s",
                    SQL.identifier(table),
                    col,
                    value,
                    rid,
                )
            )
            count += 1
    if count:
        _logger.info("Studio xmlid rename: %s.%s %s rows updated", table, column, count)


def _rename_in_text(cr, rows):
    qualified = {f"{m}.{o}": f"{m}.{n}" for m, o, n in rows}
    names = "|".join(map(re.escape, sorted(qualified, key=len, reverse=True)))
    rule = re.compile(r"(?<![\w-])(" + names + r")(?![\w])")
    modules = sorted({m for m, _o, _n in rows})
    prefilter = "(" + "|".join(re.escape(m) for m in modules) + r")\."
    for table, columns in TEXT_COLUMNS.items():
        for column in columns:
            _rename_column_text(cr, rule, qualified, prefilter, table, column)


def migrate(cr, version):
    if not version:
        return
    rows, digest = _load_map()
    cr.execute("SELECT value FROM ir_config_parameter WHERE key = %s", (MARKER,))
    row = cr.fetchone()
    if row and row[0] == digest:
        return
    _rename_xmlids(cr, rows)
    _rename_in_text(cr, rows)
    cr.execute("DELETE FROM ir_config_parameter WHERE key = %s", (MARKER,))
    cr.execute(
        "INSERT INTO ir_config_parameter (key, value, create_date, write_date) "
        "VALUES (%s, %s, now() at time zone 'UTC', now() at time zone 'UTC')",
        (MARKER, digest),
    )
