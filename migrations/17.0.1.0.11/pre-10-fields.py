"""Rename the Studio field names (x_studio_*, x_*) to their final names in the database.

Generated by _tools/rename/gen_migrations.py. The same script ships in every module of
the rename set; whichever module upgrades first does the work, the others find the
marker and return. One old name maps to one new name everywhere (MAP_FILE next to this
file).

Runs before the module's models are loaded, so the ORM finds the columns under the new
names:
- ir_model_fields.name, stored columns and their Odoo index names,
  ir_attachment.res_field, ir_property.name, field / selection xmlids: only for the
  (model, field) pairs declared in code
- every other xmlid built from a field name (same token rule as the code)
- field names inside stored text: views, server actions, domains, contexts, filters,
  rules, automations, mail/sms templates, export lists, report names; rows that belong
  to database-only x_ models (not in code) are left as they are, and so are names that
  are still a Studio ('manual') field on the row's model
"""

import csv
import hashlib
import logging
import os
import re
import zlib

from odoo.tools import SQL

_logger = logging.getLogger(__name__)

MAP_FILE = "rename_fields_all.csv"
MARKER = "studio_rename.all_fields"
X_PREFIX_RE = "(^|[^A-Za-z0-9])x_"


def _model_of(column):
    return SQL("(SELECT model FROM ir_model WHERE id = t.%s)", SQL.identifier(column))


# table: (SQL giving the row's model, alias t; text columns)
TEXT_COLUMNS = {
    "ir_ui_view": (SQL("t.model"), ["arch_db", "arch_prev"]),
    "ir_ui_view_custom": (
        SQL("(SELECT model FROM ir_ui_view WHERE id = t.ref_id)"),
        ["arch"],
    ),
    "ir_act_server": (_model_of("model_id"), ["code", "update_path", "value"]),
    "ir_server_object_lines": (
        SQL(
            "(SELECT m.model FROM ir_act_server a JOIN ir_model m ON m.id = a.model_id "
            "WHERE a.id = t.server_id)"
        ),
        ["value"],
    ),
    "ir_act_window": (SQL("t.res_model"), ["domain", "context"]),
    "ir_filters": (SQL("t.model_id"), ["domain", "context", "sort"]),
    "ir_rule": (_model_of("model_id"), ["domain_force"]),
    "base_automation": (_model_of("model_id"), ["filter_domain", "filter_pre_domain"]),
    "mail_template": (
        _model_of("model_id"),
        [
            "subject",
            "body_html",
            "email_from",
            "email_to",
            "email_cc",
            "partner_to",
            "reply_to",
            "lang",
            "scheduled_date",
            "report_name",
        ],
    ),
    "sms_template": (_model_of("model_id"), ["body"]),
    "mail_alias": (_model_of("alias_model_id"), ["alias_defaults"]),
    "ir_exports_line": (
        SQL("(SELECT resource FROM ir_exports WHERE id = t.export_id)"),
        ["name"],
    ),
    "ir_model_fields": (
        SQL("t.model"),
        ["related", "depends", "compute", "relation_field", "domain"],
    ),
    "ir_model": (SQL("t.model"), ["order"]),
    "ir_act_report_xml": (
        SQL("t.model"),
        ["print_report_name", "attachment", "report_name", "report_file"],
    ),
    "studio_approval_rule": (_model_of("model_id"), ["domain"]),
    "account_report_expression": (SQL("''"), ["formula"]),
}


class RenameConflictError(Exception):
    """A new name already exists in the database: resolve it before upgrading."""


def _load_map():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), MAP_FILE)
    with open(path, encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    mapping = {r["old_name"]: r["new_name"] for r in rows}
    pairs = {(m, r["old_name"]) for r in rows for m in r["models"].split(";")}
    digest = hashlib.sha1(
        repr(sorted(mapping.items())).encode(), usedforsecurity=False
    ).hexdigest()
    return mapping, pairs, digest


def _rule(mapping):
    # same token rule as the code rename: not inside a longer word,
    # a following "__" is allowed
    names = "|".join(map(re.escape, sorted(mapping, key=len, reverse=True)))
    return re.compile(r"(?<![A-Za-z0-9])(" + names + r")(?![A-Za-z0-9]|_(?!_))")


def _column_type(cr, table, column):
    cr.execute(
        "SELECT data_type FROM information_schema.columns "
        "WHERE table_name = %s AND column_name = %s",
        (table, column),
    )
    row = cr.fetchone()
    return row and row[0]


def _exists(cr, relname):
    cr.execute("SELECT 1 FROM pg_class WHERE relname = %s", (relname,))
    return bool(cr.fetchone())


def _index_name(table, column):
    # odoo.tools.sql.make_index_name
    name = f"{table}__{column}_index"
    if len(name) > 63:
        name = f"{name[:54]}_{zlib.crc32(name.encode()):08x}"
    return name


def _rename_column(cr, table, old, new):
    if _column_type(cr, table, new):
        raise RenameConflictError(f"Column {table}.{new} already exists ({old}).")
    cr.execute(
        SQL(
            "ALTER TABLE %s RENAME COLUMN %s TO %s",
            SQL.identifier(table),
            SQL.identifier(old),
            SQL.identifier(new),
        )
    )
    old_idx, new_idx = _index_name(table, old), _index_name(table, new)
    if _exists(cr, old_idx) and not _exists(cr, new_idx):
        cr.execute(
            SQL(
                "ALTER INDEX %s RENAME TO %s",
                SQL.identifier(old_idx),
                SQL.identifier(new_idx),
            )
        )


def _rename_fields(cr, mapping, pairs):
    """Rename the fields declared in code; return the renamed ir_model_fields ids."""
    cr.execute(
        "SELECT id, model, name, store, ttype FROM ir_model_fields "
        "WHERE name = ANY(%s)",
        (list(mapping),),
    )
    fields = [f for f in cr.fetchall() if (f[1], f[2]) in pairs]
    for fid, model, old, store, ttype in fields:
        new = mapping[old]
        cr.execute(
            "SELECT 1 FROM ir_model_fields WHERE model = %s AND name = %s", (model, new)
        )
        if cr.fetchone():
            raise RenameConflictError(f"Field {model}.{new} already exists ({old}).")
        table = model.replace(".", "_")
        stored_column = store and ttype not in ("many2many", "one2many")
        if stored_column and _column_type(cr, table, old):
            _rename_column(cr, table, old, new)
        # Studio fields are 'manual', and Odoo only allows x_ names for those
        # (CHECK name_manual_field). The field is declared in code, so it is a base
        # field: Odoo would set this itself when loading the module.
        cr.execute(
            "UPDATE ir_model_fields SET name = %s, state = 'base' WHERE id = %s",
            (new, fid),
        )
        cr.execute(
            "UPDATE ir_attachment SET res_field = %s "
            "WHERE res_model = %s AND res_field = %s",
            (new, model, old),
        )
    _logger.info("Studio field rename: %s field records renamed", len(fields))
    return [f[0] for f in fields]


def _rename_xmlids(cr, mapping, rule, field_ids):
    """Same token rule as the code; field / selection xmlids only for renamed fields."""
    cr.execute(
        "SELECT id FROM ir_model_fields_selection WHERE field_id = ANY(%s)",
        (field_ids,),
    )
    own = {("ir.model.fields", i) for i in field_ids}
    own |= {("ir.model.fields.selection", r[0]) for r in cr.fetchall()}
    cr.execute(
        "SELECT id, module, name, model, res_id FROM ir_model_data WHERE name ~ %s",
        (X_PREFIX_RE,),
    )
    done = skipped = 0
    for xid, module, name, model, res_id in cr.fetchall():
        field_meta = model in ("ir.model.fields", "ir.model.fields.selection")
        if field_meta and (model, res_id) not in own:
            continue
        new = rule.sub(lambda m: mapping[m.group(1)], name)
        if new == name:
            continue
        cr.execute(
            "SELECT 1 FROM ir_model_data WHERE module = %s AND name = %s", (module, new)
        )
        if cr.fetchone():
            _logger.warning(
                "Studio field rename: xmlid %s.%s -> %s exists already, kept",
                module,
                name,
                new,
            )
            skipped += 1
            continue
        cr.execute("UPDATE ir_model_data SET name = %s WHERE id = %s", (new, xid))
        done += 1
    _logger.info("Studio field rename: %s xmlids renamed, %s kept", done, skipped)


def _rename_column_text(cr, mapping, rule, code_models, keep, table, model_sql, column):
    ctype = _column_type(cr, table, column)
    if not ctype:
        return
    col = SQL.identifier("t", column)
    cr.execute(
        SQL(
            "SELECT t.id, %s::text, %s FROM %s t WHERE %s::text ~ %s",
            col,
            model_sql,
            SQL.identifier(table),
            col,
            X_PREFIX_RE,
        )
    )
    count = kept = 0
    for rid, text, model in cr.fetchall():
        if model and model.startswith("x_") and model not in code_models:
            kept += 1
            continue
        kept_names = keep.get(model, ())
        new = rule.sub(
            lambda m, kept=kept_names: (
                m.group(1) if m.group(1) in kept else mapping[m.group(1)]
            ),
            text,
        )
        if new != text:
            value = SQL("%s::jsonb", new) if ctype == "jsonb" else SQL("%s", new)
            cr.execute(
                SQL(
                    "UPDATE %s SET %s = %s WHERE id = %s",
                    SQL.identifier(table),
                    SQL.identifier(column),
                    value,
                    rid,
                )
            )
            count += 1
    if count or kept:
        _logger.info(
            "Studio field rename: %s.%s %s rows updated, "
            "%s rows of database-only models kept",
            table,
            column,
            count,
            kept,
        )


def migrate(cr, version):
    if not version:
        return
    mapping, pairs, digest = _load_map()
    cr.execute("SELECT value FROM ir_config_parameter WHERE key = %s", (MARKER,))
    row = cr.fetchone()
    if row and row[0] == digest:
        return
    rule = _rule(mapping)
    field_ids = _rename_fields(cr, mapping, pairs)
    _rename_xmlids(cr, mapping, rule, field_ids)
    if _column_type(cr, "ir_property", "name"):
        cr.execute(
            "UPDATE ir_property p SET name = f.name FROM ir_model_fields f "
            "WHERE f.id = p.fields_id AND f.id = ANY(%s) AND p.name <> f.name",
            (field_ids,),
        )
    code_models = {m for m, _f in pairs}
    # Studio 'manual' fields with a mapped name stay x_ (Odoo requires it): text of
    # their model keeps that name
    cr.execute(
        "SELECT model, name FROM ir_model_fields WHERE state = 'manual' AND name = ANY(%s)",
        (list(mapping),),
    )
    keep = {}
    for model, name in cr.fetchall():
        keep.setdefault(model, set()).add(name)
    for table, (model_sql, columns) in TEXT_COLUMNS.items():
        for column in columns:
            _rename_column_text(
                cr, mapping, rule, code_models, keep, table, model_sql, column
            )
    cr.execute("DELETE FROM ir_config_parameter WHERE key = %s", (MARKER,))
    cr.execute(
        "INSERT INTO ir_config_parameter (key, value, create_date, write_date) "
        "VALUES (%s, %s, now() at time zone 'UTC', now() at time zone 'UTC')",
        (MARKER, digest),
    )
